
-- ============================================
-- ORALSOLUTIONS - PSET2
-- Creación de las tablas de la capa RAW
-- ============================================

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE ORALSOLUTIONS_DW;
USE SCHEMA RAW;

-- 1. PACIENTES
CREATE TABLE IF NOT EXISTS PATIENTS (
    ID VARCHAR,
    FIRST_NAME VARCHAR,
    LAST_NAME VARCHAR,
    EMAIL VARCHAR,
    BIRTH_DATE VARCHAR,
    INSURER_ID VARCHAR,
    COVER_FRACTION VARCHAR,
    REGISTERED_AT VARCHAR
);

-- 2. ODONTÓLOGOS
CREATE TABLE IF NOT EXISTS DENTISTS (
    ID VARCHAR,
    FIRST_NAME VARCHAR,
    LAST_NAME VARCHAR,
    CONTRACT VARCHAR,
    JOINED_ON VARCHAR
);

-- 3. ASEGURADORAS
CREATE TABLE IF NOT EXISTS INSURERS (
    ID VARCHAR,
    SCHEME VARCHAR,
    PLAN_NAME VARCHAR,
    COVER_FRACTION VARCHAR
);

-- 4. CITAS
CREATE TABLE IF NOT EXISTS APPOINTMENTS (
    ID VARCHAR,
    PATIENT_ID VARCHAR,
    DENTIST_ID VARCHAR,
    SCHEDULED_AT VARCHAR,
    VISIT_TYPE VARCHAR,
    COVER_FRACTION VARCHAR
);

-- 5. CITAS PERDIDAS
CREATE TABLE IF NOT EXISTS MISSED_APPOINTMENTS (
    ID VARCHAR,
    PATIENT_ID VARCHAR,
    DENTIST_ID VARCHAR,
    SCHEDULED_AT VARCHAR,
    OUTCOME VARCHAR
);

-- 6. FACTURAS
CREATE TABLE IF NOT EXISTS INVOICES (
    ID VARCHAR,
    APPOINTMENT_ID VARCHAR,
    INVOICE_NO VARCHAR,
    ISSUED_ON VARCHAR,
    STATUS VARCHAR,
    PAID_ON VARCHAR
);

-- 7. PROCEDIMIENTOS
CREATE TABLE IF NOT EXISTS PROCEDURES (
    ID VARCHAR,
    CODE VARCHAR,
    NAME VARCHAR,
    FEE VARCHAR,
    CHAIR_MINUTES VARCHAR,
    LIST_NAME VARCHAR
);

-- 8. LÍNEAS DE TRATAMIENTO
CREATE TABLE IF NOT EXISTS TREATMENT_LINES (
    ID VARCHAR,
    APPOINTMENT_ID VARCHAR,
    PROCEDURE_ID VARCHAR,
    FEE VARCHAR,
    INSURER_AMOUNT VARCHAR,
    PATIENT_AMOUNT VARCHAR
);

-- 9. PLANES DE TRATAMIENTO
CREATE TABLE IF NOT EXISTS TREATMENT_PLANS (
    ID VARCHAR,
    PATIENT_ID VARCHAR,
    DENTIST_ID VARCHAR,
    PROCEDURE_ID VARCHAR,
    START_DATE VARCHAR,
    PLANNED_SESSIONS VARCHAR,
    ESTIMATED_COST VARCHAR,
    STATUS VARCHAR,
    END_DATE VARCHAR,
    CLOSURE_REASON VARCHAR
);

-- 10. SESIONES DE TRATAMIENTO
CREATE TABLE IF NOT EXISTS TREATMENT_SESSIONS (
    ID VARCHAR,
    TREATMENT_PLAN_ID VARCHAR,
    APPOINTMENT_ID VARCHAR,
    MISSED_APPOINTMENT_ID VARCHAR,
    SESSION_NUMBER VARCHAR,
    PLANNED_DATE VARCHAR,
    COMPLETED_AT VARCHAR,
    STATUS VARCHAR
);

-- 11. SEGUIMIENTOS
CREATE TABLE IF NOT EXISTS PATIENT_FOLLOWUPS (
    ID VARCHAR,
    TREATMENT_PLAN_ID VARCHAR,
    CONTACT_DATE VARCHAR,
    CONTACT_METHOD VARCHAR,
    CONTACT_RESULT VARCHAR
);

-- ============================================
-- FORMATO DE INGESTA CSV
-- ============================================

CREATE FILE FORMAT IF NOT EXISTS CSV_RAW_FORMAT
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = FALSE
    TRIM_SPACE = FALSE
    NULL_IF = ()
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

-- ============================================
-- STAGE INTERNO PARA LA INGESTA DE ARCHIVOS CSV
-- ============================================

CREATE STAGE IF NOT EXISTS
    ORALSOLUTIONS_DW.RAW.RAW_CSV_STAGE;

-- Verificar que el stage exista
SHOW STAGES LIKE 'RAW_CSV_STAGE'
IN SCHEMA ORALSOLUTIONS_DW.RAW;