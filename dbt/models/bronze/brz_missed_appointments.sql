    TRY_CAST(ID AS INTEGER) AS ID,

    TRY_CAST(PATIENT_ID AS INTEGER)
        AS PATIENT_ID,

    TRY_CAST(DENTIST_ID AS INTEGER)
        AS DENTIST_ID,

    TRY_CAST(SCHEDULED_AT AS TIMESTAMP_NTZ)
        AS SCHEDULED_AT,

    OUTCOME

