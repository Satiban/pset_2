SELECT
    TRY_CAST(ID AS INTEGER) AS ID,
    TRY_CAST(PATIENT_ID AS INTEGER) AS PATIENT_ID,
    TRY_CAST(DENTIST_ID AS INTEGER) AS DENTIST_ID,
    TRY_CAST(SCHEDULED_AT AS TIMESTAMP_NTZ) AS SCHEDULED_AT,
    VISIT_TYPE,
    TRY_CAST(COVER_FRACTION AS FLOAT) AS COVER_FRACTION

FROM {{ source('raw', 'APPOINTMENTS') }}