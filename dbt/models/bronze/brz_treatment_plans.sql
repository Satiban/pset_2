SELECT
    TRY_CAST(ID AS INTEGER) AS ID,
    TRY_CAST(PATIENT_ID AS INTEGER) AS PATIENT_ID,
    TRY_CAST(DENTIST_ID AS INTEGER) AS DENTIST_ID,
    TRY_CAST(PROCEDURE_ID AS INTEGER) AS PROCEDURE_ID,
    TRY_CAST(START_DATE AS DATE) AS START_DATE,
    TRY_CAST(PLANNED_SESSIONS AS INTEGER) AS PLANNED_SESSIONS,
    TRY_CAST(ESTIMATED_COST AS DECIMAL(12,2)) AS ESTIMATED_COST,
    STATUS,
    TRY_CAST(END_DATE AS DATE) AS END_DATE,
    CLOSURE_REASON

FROM {{ source('raw', 'TREATMENT_PLANS') }}