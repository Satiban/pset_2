    materialized='table',
    alias='BRZ_TREATMENT_SESSIONS'
) }}

SELECT
    TRY_CAST(ID AS INTEGER) AS ID,

    TRY_CAST(TREATMENT_PLAN_ID AS INTEGER)
        AS TREATMENT_PLAN_ID,

    TRY_CAST(SESSION_NUMBER AS INTEGER)
        AS SESSION_NUMBER,

    TRY_CAST(PLANNED_DATE AS DATE)
        AS PLANNED_DATE,

    STATUS,

    TRY_CAST(APPOINTMENT_ID AS INTEGER)
        AS APPOINTMENT_ID,

    TRY_CAST(MISSED_APPOINTMENT_ID AS INTEGER)
        AS MISSED_APPOINTMENT_ID,

    TRY_CAST(COMPLETED_AT AS TIMESTAMP_NTZ)
        AS COMPLETED_AT

FROM {{ source('raw', 'TREATMENT_SESSIONS') }}