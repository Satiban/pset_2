SELECT
    TRY_CAST(ID AS INTEGER) AS ID,
    FIRST_NAME,
    LAST_NAME,
    EMAIL,
    TRY_CAST(BIRTH_DATE AS DATE) AS BIRTH_DATE,
    TRY_CAST(INSURER_ID AS INTEGER) AS INSURER_ID,
    TRY_CAST(COVER_FRACTION AS FLOAT) AS COVER_FRACTION,
    TRY_CAST(REGISTERED_AT AS TIMESTAMP_NTZ) AS REGISTERED_AT

FROM {{ source('raw', 'PATIENTS') }}